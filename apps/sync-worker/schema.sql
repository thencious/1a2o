CREATE TABLE IF NOT EXISTS heads (doc TEXT PRIMARY KEY, rev TEXT NOT NULL, payload TEXT NOT NULL, at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS versions (doc TEXT NOT NULL, rev TEXT NOT NULL, parent TEXT, payload TEXT NOT NULL, at INTEGER NOT NULL, PRIMARY KEY(doc,rev));
CREATE INDEX IF NOT EXISTS versions_by_time ON versions(doc,at DESC);

CREATE TABLE IF NOT EXISTS chunks (doc TEXT NOT NULL, rev TEXT NOT NULL, seq INTEGER NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(doc,rev,seq));

CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, token_hash TEXT NOT NULL UNIQUE, docs TEXT NOT NULL, revoked INTEGER NOT NULL DEFAULT 0, at INTEGER NOT NULL);
